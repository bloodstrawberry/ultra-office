// ============================================================
// Helper builders for rich Baduk problem generation
// ============================================================

function createBadukProblem(
  id: string,
  title: string,
  difficulty: '입문' | '초급' | '중급' | '고급',
  category: '사활' | '수상전' | '맥점' | '환격' | '귀삼수' | '축/장문',
  boardSize: number,
  focusRegion: { minR: number; maxR: number; minC: number; maxC: number },
  blackStones: [number, number][],
  whiteStones: [number, number][],
  objective: string,
  hint: string,
  solutionMove: [number, number],
  comment: string,
  explanation: string,
  csConcept: string,
  aiResponseMove?: [number, number],
  aiComment?: string,
  followUpMove?: [number, number],
  followUpComment?: string
): BadukProblem {
  return {
    id,
    title,
    difficulty,
    category,
    boardSize,
    focusRegion,
    initialBlack: blackStones.map(([r, c]) => ({ r, c })),
    initialWhite: whiteStones.map(([r, c]) => ({ r, c })),
    playerColor: 'B',
    objective,
    hint,
    solutionTree: [
      {
        move: { r: solutionMove[0], c: solutionMove[1] },
        comment,
        isCorrect: true,
        aiResponse: aiResponseMove ? { r: aiResponseMove[0], c: aiResponseMove[1] } : undefined,
        aiComment,
        children: followUpMove
          ? [
              {
                move: { r: followUpMove[0], c: followUpMove[1] },
                comment: followUpComment || '정답 완료! 완벽하게 사활을 해결했습니다.',
                isCorrect: true,
              },
            ]
          : undefined,
      },
    ],
    explanation,
    csConcept,
  };
}

